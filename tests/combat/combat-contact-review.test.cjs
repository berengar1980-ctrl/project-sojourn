'use strict';
const assert = require('node:assert/strict');
const { load, pair } = require('./maneuver-fixtures.cjs');
const { collisionThreat } = load('src/systems/combat/combat-contact-review.ts');
const { predictedCollisionEvasion } = load('src/systems/combat/combat-collision-evasion.ts');
const [a, b] = pair();
a.position = { x: 800, y: 800 };
b.position = { x: 1100, y: 800 };
a.velocity = { x: 100, y: 0 };
b.velocity = { x: -100, y: 0 };
assert(collisionThreat(a, b));
const first = predictedCollisionEvasion(a, b, 'attacker', { x: 1, y: 0 }, 1);
const second = predictedCollisionEvasion(b, a, 'defender', { x: -1, y: 0 }, 1);
assert(first.direction.y * second.direction.y < 0, 'opposing ships must take opposite world lanes');
b.velocity = { x: 150, y: 0 };
assert(!collisionThreat(a, b), 'separating motion does not trigger avoidance');
console.log('PASS physical collision prediction and symmetric passing convention');
