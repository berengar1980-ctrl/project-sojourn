export function personalRangedProfile(itemId: string | null): BoardingWeaponProfile {
  const id = itemId ?? 'off_autopistol';
  const baseId = id.startsWith('salvage_')
    ? Object.keys(personalRangedProfiles)
        .sort((first, second) => second.length - first.length)
        .find((key) => id.startsWith('salvage_' + key + '_'))
    : id;
  const base = personalRangedProfiles[baseId ?? ''] ?? personalRangedProfiles.off_autopistol!;
  if (!baseId || !id.startsWith('salvage_')) return base;
  if (!id.endsWith('_power')) return { ...base, id, name: base.name + ' – Kalibriert' };
  return {
    ...base,
    id,
    name: base.name + ' – Überarbeitet',
    damage: Math.min(10, base.damage + 1),
    hitBonus: base.hitBonus + 1,
  };
}

export function personalMeleeProfile(itemId: string | null): BoardingMeleeProfile {
  return personalMeleeProfiles[itemId ?? ''] ?? personalMeleeProfiles.combat_knife!;
}
